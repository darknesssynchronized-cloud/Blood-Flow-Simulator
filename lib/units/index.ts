export const mmToMeters = (mm: number) => mm * 1e-3;
export const cmToMeters = (cm: number) => cm * 1e-2;
export const cPToPas = (cP: number) => cP * 1e-3;
export const mmHgToPascal = (mmHg: number) => mmHg * 133.322;
export const m3sToMls = (m3s: number) => m3s * 1e6;
export const m3sToMlmin = (m3s: number) => m3s * 6e7;
